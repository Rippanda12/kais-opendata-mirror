import pytest

from kaismirror.convert import parse_adjpart


@pytest.mark.parametrize("text, sqm, pct", [
    ("13,09 кв.м (2,89%) идеални части от общите части на сградата", 13.09, 2.89),
    ("1.129% (7.14кв.м.) идеални части от общите части", 7.14, 1.129),
    ("8,48 кв.м (1,87%) идеални части … и склад # 3 с площ от 3,92 кв.м", 8.48, 1.87),
    ("4,22 кв.м. ид.ч. от сградата", 4.22, None),
    ("2.526% ид.ч. от общ. ч. на сгр.= 8.28м2", 8.28, 2.526),
    ("изба № 31 със застроена площ 3,80кв.м., както и 2,564% (15,13кв.м.) ид.ч.", 15.13, 2.564),
    ("изба 3,00 кв.м.", None, None),
    ("избено помещение - 4.94 кв.м., 0994% ид. части от об.ч.", None, 0.994),
    ("изб. пом. с площ 3.89 кв. м. и о.911% ид. ч.от общите части", None, 0.911),
    ("изба №20 с площ 2,79 кв.м. и 0 ,970% ид.ч. общи части сграда", None, 0.970),
    ("таванско помещение №43 с площ 1.45кв.м; 13059% ид. части", None, None),
    ("съответните ид.ч. от общите части на сградата", None, None),
    (None, None, None),
])
def test_parse_adjpart(text, sqm, pct):
    assert parse_adjpart(text) == (sqm, pct)
